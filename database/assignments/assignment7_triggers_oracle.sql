-- 2. 'BEFORE INSERT OR UPDATE FOR EACH ROW' combined timing.
-- 3. 'RAISE_APPLICATION_ERROR(-20001, 'message')' for user-defined exceptions.
-- 4. Autonomous or standard auditing via AFTER UPDATE / AFTER DELETE triggers.
