-- ------------------------------------------------------------------------------
-- 1. ORACLE DEMONSTRATION TABLES
-- ------------------------------------------------------------------------------

CREATE TABLE demo_deal_audit_log_ora (
    audit_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    deal_id              NUMBER NOT NULL,
    old_deal_status      VARCHAR2(20),
    new_deal_status      VARCHAR2(20),
    old_payment_status   VARCHAR2(20),
    new_payment_status   VARCHAR2(20),
    change_type          VARCHAR2(30) NOT NULL,
    changed_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE demo_marketplace_deal_ora (
    deal_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id         NUMBER NOT NULL,
    seller_id        NUMBER NOT NULL,
    agreed_price     NUMBER(10,2) NOT NULL,
    deal_status      VARCHAR2(20) DEFAULT 'Pending' NOT NULL,
    payment_status   VARCHAR2(20) DEFAULT 'Pending' NOT NULL,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------------------------
-- 2. ORACLE TRIGGER 1: BEFORE INSERT - Validation & Integrity
-- ------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_deal_before_ins_ora
BEFORE INSERT ON demo_marketplace_deal_ora
FOR EACH ROW
BEGIN
    -- Rule A: Check minimum transaction amount
    IF :NEW.agreed_price < 500.00 THEN
        RAISE_APPLICATION_ERROR(-20001, 'Validation Error: Minimum transaction amount on ServicePath AI is 500.00');
    END IF;

    -- Rule B: Prevent self-dealing
    IF :NEW.buyer_id = :NEW.seller_id THEN
        RAISE_APPLICATION_ERROR(-20002, 'Validation Error: Buyer and Seller cannot be the same business entity');
    END IF;
END;
/

-- ------------------------------------------------------------------------------
-- 3. ORACLE TRIGGER 2: BEFORE UPDATE - Immutability Enforcement
-- ------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_deal_before_upd_ora
BEFORE UPDATE ON demo_marketplace_deal_ora
FOR EACH ROW
BEGIN
    -- Rule A: Agreed price immutability after deal completion
    IF :OLD.deal_status = 'Completed' AND :NEW.agreed_price <> :OLD.agreed_price THEN
        RAISE_APPLICATION_ERROR(-20003, 'Business Rule Violation: Agreed price cannot be modified on a Completed deal');
    END IF;

    -- Rule B: Prevent reactivation of cancelled deal
    IF :OLD.deal_status = 'Cancelled' AND :NEW.deal_status = 'Completed' THEN
        RAISE_APPLICATION_ERROR(-20004, 'Invalid State Transition: Cancelled deals cannot be marked Completed');
    END IF;

    -- Rule C: Auto-maintain update timestamp
    :NEW.updated_at := CURRENT_TIMESTAMP;
END;
/

-- ------------------------------------------------------------------------------
-- 4. ORACLE TRIGGER 3: AFTER UPDATE - Transaction Lifecycle Audit Log
-- ------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_deal_after_upd_ora
AFTER UPDATE ON demo_marketplace_deal_ora
FOR EACH ROW
BEGIN
    IF (:OLD.deal_status <> :NEW.deal_status) OR (:OLD.payment_status <> :NEW.payment_status) THEN
        INSERT INTO demo_deal_audit_log_ora (
            deal_id,
            old_deal_status,
            new_deal_status,
            old_payment_status,
            new_payment_status,
            change_type
        ) VALUES (
            :OLD.deal_id,
            :OLD.deal_status,
            :NEW.deal_status,
            :OLD.payment_status,
            :NEW.payment_status,
            'STATUS_CHANGE'
        );
    END IF;
END;
/

-- ------------------------------------------------------------------------------
-- 5. ORACLE TRIGGER 4: AFTER DELETE - Deletion Tombstone
-- ------------------------------------------------------------------------------

CREATE OR REPLACE TRIGGER trg_deal_after_del_ora
AFTER DELETE ON demo_marketplace_deal_ora
FOR EACH ROW
BEGIN
    INSERT INTO demo_deal_audit_log_ora (
        deal_id,
        old_deal_status,
        new_deal_status,
        old_payment_status,
        new_payment_status,
        change_type
    ) VALUES (
        :OLD.deal_id,
        :OLD.deal_status,
        'PURGED',
        :OLD.payment_status,
        'PURGED',
        'RECORD_DELETED'
    );
END;
/

